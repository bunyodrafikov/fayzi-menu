"""Build menu.js and web-sized photos from menu.xlsx + photos/.

Edit menu.xlsx (Категория | Название | Цена | Состав | Фото | Калории | Белки | Жиры | Углеводы), then run:
    .venv/bin/python build.py
Rows keep sheet order; categories appear in order of first use.
Фото = file name inside photos/ (full-quality original, jpg/png/webp; empty = no photo).
Калории/Белки/Жиры/Углеводы = per portion (kcal, g); leave all four empty to hide them.
Output goes to site/ — the whole folder to deploy (index.html, menu.js, images/, fonts/).
Generated into site/images/:
    <name>-720.webp, <name>-1200.webp  sharp on any phone/desktop via srcset
    <name>-160.webp                    category chip
Photos keep their own shape; the page crops them (object-fit) to the card.
"""
import json, os, sys
from openpyxl import load_workbook
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(ROOT, "site")
SIZES = {720: 82, 1200: 80, 160: 70}  # width px -> WebP quality


def web_photos(photo):
    """Make web sizes of photos/<photo> in site/images/; returns base path "images/<name>" (relative to site/)."""
    src = os.path.join(ROOT, "photos", photo)
    base = f"images/{os.path.splitext(photo)[0]}"
    todo = [(w, q) for w, q in SIZES.items()
            if not os.path.exists(p := os.path.join(SITE, f"{base}-{w}.webp")) or os.path.getmtime(p) < os.path.getmtime(src)]
    if todo:
        with Image.open(src) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            for w, q in todo:
                px = min(w, im.width)  # never upscale; file keeps the nominal width name
                im.resize((px, round(im.height * px / im.width)), Image.LANCZOS).save(
                    os.path.join(SITE, f"{base}-{w}.webp"), "WEBP", quality=q, method=6)
    return base


def main():
    os.makedirs(os.path.join(SITE, "images"), exist_ok=True)
    ws = load_workbook(os.path.join(ROOT, "menu.xlsx"), read_only=True, data_only=True).active
    cats, errors = {}, []
    for n, row in enumerate(ws.iter_rows(min_row=2, max_col=9, values_only=True), start=2):
        row = (tuple(row) + (None,) * 9)[:9]
        cat, name, price, ingr, photo, *nutr = [(v.strip() if isinstance(v, str) else v) for v in row]
        if not any((cat, name, price, ingr, photo)):
            continue  # blank row
        if not cat or not name:
            errors.append(f"row {n}: Категория and Название are required")
            continue
        try:
            price = float(str(price).replace(",", ".").replace(" ", ""))
        except ValueError:
            errors.append(f"row {n}: Цена is not a number: {price!r}")
            continue
        if all(v in (None, "") for v in nutr):
            nutr = None
        else:
            try:
                nutr = [round(float(str(v).replace(",", "."))) for v in nutr]
            except ValueError:
                errors.append(f"row {n}: Калории/Белки/Жиры/Углеводы must all be numbers: {nutr!r}")
                continue
        if photo and not os.path.isfile(os.path.join(ROOT, "photos", photo)):
            errors.append(f"row {n}: photo not found: photos/{photo}")
            continue
        cats.setdefault(cat, []).append({
            "name": name,
            "price": price,
            "ingredients": ingr or "",
            "photo": photo or "",
            **({"nutrition": nutr} if nutr else {}),  # [kcal, protein g, fat g, carbs g]
        })

    if errors:
        sys.exit("menu.xlsx has problems, menu.js not changed:\n  " + "\n  ".join(errors))

    menu = []
    for c, items in cats.items():
        for it in items:
            it["photo"] = web_photos(it["photo"]) if it["photo"] else ""
        cover = next((i["photo"] for i in items if i["photo"]), "")  # first dish photo stands in for the category
        menu.append({"name": c, "thumb": f"{cover}-160.webp" if cover else "", "items": items})
    with open(os.path.join(SITE, "menu.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by build.py from menu.xlsx. Do not edit by hand.\n")
        f.write("window.MENU = " + json.dumps(menu, ensure_ascii=False, indent=1) + ";\n")
    print(f"menu.js: {len(menu)} categories, {sum(len(i) for i in cats.values())} items")


if __name__ == "__main__":
    main()
