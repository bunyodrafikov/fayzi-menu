"""Build menu.js and web-sized photos from menu.json + photos/.

menu.json is edited through the admin page (site/admin/, saved by worker/) or by hand:
    [{"name": category, "items": [{"name", "price", "ingredients", "photo", "nutrition"?}]}]
photo = file name inside photos/ (full-quality original, jpg/png/webp; "" = no photo).
nutrition = [kcal, protein g, fat g, carbs g] per 100 g; leave it out to hide it.
Runs in the GitHub Pages workflow on every push; locally: .venv/bin/python build.py
Output goes to site/ — the whole folder to deploy (index.html, menu.js, images/, fonts/, admin/).
Generated into site/images/:
    <name>-720.webp, <name>-1200.webp  sharp on any phone/desktop via srcset
    <name>-160.webp                    category chip
Photos keep their own shape; the page crops them (object-fit) to the card.
"""
import json, os, sys
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(ROOT, "site")
SIZES = {720: 82, 1200: 80, 160: 70}  # width px -> WebP quality


def web_photos(photo):
    """Make web sizes of photos/<photo> in site/images/; returns base path "images/<name>" (relative to site/)."""
    src = os.path.join(ROOT, "photos", photo)
    base = f"images/{os.path.splitext(photo)[0]}"
    todo = [(w, q) for w, q in SIZES.items()
            if not os.path.exists(p := os.path.join(SITE, f"{base}-{w}.webp")) or os.path.getmtime(p) < os.path.getmtime(src)]
    if todo:
        with Image.open(src) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            for w, q in todo:
                px = min(w, im.width)  # never upscale; file keeps the nominal width name
                im.resize((px, round(im.height * px / im.width)), Image.LANCZOS).save(
                    os.path.join(SITE, f"{base}-{w}.webp"), "WEBP", quality=q, method=6)
    return base


def main():
    os.makedirs(os.path.join(SITE, "images"), exist_ok=True)
    with open(os.path.join(ROOT, "menu.json"), encoding="utf-8") as f:
        menu = json.load(f)
    errors = []
    for cat in menu:
        for it in cat["items"]:
            where = f'{cat["name"]} / {it.get("name")}'
            if not cat["name"] or not it.get("name"):
                errors.append(f"{where}: category and dish name are required")
            if not isinstance(it.get("price"), (int, float)):
                errors.append(f"{where}: price is not a number: {it.get('price')!r}")
            if it.get("photo") and not os.path.isfile(os.path.join(ROOT, "photos", it["photo"])):
                errors.append(f"{where}: photo not found: photos/{it['photo']}")
    if errors:
        sys.exit("menu.json has problems, menu.js not changed:\n  " + "\n  ".join(errors))

    out = []
    for cat in menu:
        items = [{**it, "photo": web_photos(it["photo"]) if it.get("photo") else ""} for it in cat["items"]]
        cover = next((i["photo"] for i in items if i["photo"]), "")  # first dish photo stands in for the category
        out.append({"name": cat["name"], "thumb": f"{cover}-160.webp" if cover else "", "items": items})
    with open(os.path.join(SITE, "menu.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by build.py from menu.json. Do not edit by hand.\n")
        f.write("window.MENU = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
    print(f"menu.js: {len(out)} categories, {sum(len(c['items']) for c in out)} items")


if __name__ == "__main__":
    main()
